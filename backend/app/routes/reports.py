from fastapi import APIRouter, Depends
from fastapi.responses import StreamingResponse
from sqlalchemy.orm import Session
from app.database import get_db
from app.models.models import User
from app.services.auth_service import get_current_user
from app.services.report_service import generate_trust_report
from datetime import datetime, timezone
import io

router = APIRouter(prefix="/api/reports", tags=["reports"])

@router.get("/trust-report")
def get_trust_report(
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    report = generate_trust_report(db, current_user)
    report["created_at"] = datetime.now(timezone.utc).isoformat()
    return report

@router.get("/download-pdf")
def download_pdf(
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    from fpdf import FPDF
    report = generate_trust_report(db, current_user)
    report["created_at"] = datetime.now(timezone.utc).isoformat()

    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 20)
    pdf.cell(0, 12, "TrustSphere AI - Trust Report", ln=True, align="C")
    pdf.set_font("Helvetica", "", 11)
    pdf.cell(0, 8, f"Report ID: {report['report_id']} | User: {current_user.email}", ln=True, align="C")
    pdf.cell(0, 8, f"Generated: {report['created_at']}", ln=True, align="C")
    pdf.ln(8)

    pdf.set_font("Helvetica", "B", 14)
    pdf.cell(0, 10, f"Overall Trust Score: {report['overall_score']}% ({report['overall_status']})", ln=True)
    pdf.ln(4)

    sections = [
        ("SourceMark - Content Integrity", report.get("sourcemark", {})),
        ("ProvenanceGuard - Rollback & Provenance Security", report.get("provenanceguard", {})),
        ("TrustTest AI - Security Testing", report.get("trusttest", {})),
        ("EvidenceLock - Audit Chain", report.get("evidencelock", {})),
    ]

    for title, data in sections:
        pdf.set_font("Helvetica", "B", 12)
        pdf.cell(0, 9, title, ln=True)
        pdf.set_font("Helvetica", "", 10)
        if data:
            for k, v in data.items():
                pdf.cell(0, 7, f"  {k.replace('_', ' ').title()}: {v}", ln=True)
        else:
            pdf.cell(0, 7, "  No data available.", ln=True)
        pdf.ln(3)

    pdf.set_font("Helvetica", "I", 9)
    pdf.cell(0, 7, f"This report was generated by TrustSphere AI for account {current_user.email}.", ln=True)

    buf = io.BytesIO(pdf.output())
    return StreamingResponse(
        buf,
        media_type="application/pdf",
        headers={"Content-Disposition": f'attachment; filename="TrustReport_{report["report_id"]}.pdf"'},
    )
